namespace Sparnarok.Api.Domain.Enums;

/// <summary>
/// Tipología ontológica de criaturas en D&amp;D 5e (2024).
/// </summary>
public enum CreatureType
{
    /// <summary>Aberración: Seres alienígenas procedentes del Reino Lejano.</summary>
    Aberration = 1,

    /// <summary>Bestia: Animales no humanoides que forman parte del ecosistema natural.</summary>
    Beast = 2,

    /// <summary>Celestial: Seres de planos superiores de naturaleza noble y sagrada.</summary>
    Celestial = 3,

    /// <summary>Autómata / Constructo: Seres creados artificialmente mediante magia o tecnología.</summary>
    Construct = 4,

    /// <summary>Dragón: Criaturas reptilianas de linaje milenario y gran poder mágico.</summary>
    Dragon = 5,

    /// <summary>Elemental: Seres nacidos de los planos elementales (Fuego, Agua, Aire, Tierra).</summary>
    Elemental = 6,

    /// <summary>Feérico: Entidades mágicas estrechamente vinculadas con el Feywild.</summary>
    Fey = 7,

    /// <summary>Infernal / Inmunda: Demonios, diablos y horrores de los planos inferiores.</summary>
    Fiend = 8,

    /// <summary>Gigante: Humanoides colosales con fuerza hercúlea.</summary>
    Giant = 9,

    /// <summary>Humanoide: Especies bípedas principales con sociedad y civilización.</summary>
    Humanoid = 10,

    /// <summary>Monstruosidad: Engendros antinaturales, híbridos y quimeras mágicas.</summary>
    Monstrosity = 11,

    /// <summary>Cieno: Criaturas gelatinosas sin forma definida.</summary>
    Ooze = 12,

    /// <summary>Planta: Flora animada con conciencia mágica o predatoria.</summary>
    Plant = 13,

    /// <summary>Muerto Viviente: Cadáveres animados por nigromancia o almas no descansadas.</summary>
    Undead = 14
}
